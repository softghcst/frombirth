// Writes js/data/hairTops.js: the highest point of each fitted hairstyle on each head (assets/hair_fitted/*.svg),
// in the portrait's own coordinates, so a crown can be set on top of the hair (js/CharacterAvatar.js crownAt).
// Run after the hair pipeline (scripts/fit_hair.py) adds or changes styles: node scripts/hair_tops.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../assets/hair_fitted/', import.meta.url);
const tops = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(new URL(file, dir), 'utf8');
  let top = Infinity;
  // Paths are absolute (M, L, Q, C, Z): every second number is a y.
  for (const [, d] of svg.matchAll(/\sd="([^"]*)"/g)) {
    const nums = d.replace(/[MLQCZ]/g, ' ').trim().split(/[\s,]+/).filter(Boolean).map(Number);
    for (let i = 1; i < nums.length; i += 2) if (nums[i] < top) top = nums[i];
  }
  if (Number.isFinite(top)) tops[`hair_fitted/${file}`] = Math.round(top);
}
writeFileSync(new URL('../js/data/hairTops.js', import.meta.url),
  `// Generated by scripts/hair_tops.mjs: do not edit by hand. The highest point of each fitted hairstyle, by file.\nexport const HAIR_TOPS = ${JSON.stringify(tops)};\n`);
console.log(`${Object.keys(tops).length} hairstyles measured.`);
