#!/usr/bin/env python3
"""
Makes the baby hairstyles: each one drawn from the young head it sits on, so it fits it exactly.

    python3 scripts/make_baby_hair.py

Babies and toddlers have their own heads (assets/heads/baby.svg, toddler.svg). Rather than drawing a style once and
warping it, every style is built here from that head's own outline (the same row-by-row scan as the landmarks,
scripts/extract_landmarks.py): the hair follows the skull a unit or two outside its edge, down to the temples, with
a baby's high hairline. Writes assets/hair_baby/<style>_<head>.svg, in the four layers the game draws fitted hair
in (hair_back behind the head; hair_base, hair_bangs, hair_lines in front), colored with var(--hair-color) so
dye and natural color work, outlined in the heads' #23140f.

Standard library only.
"""
import math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import extract_landmarks as EL  # noqa: E402

OUT = os.path.join(ROOT, 'assets', 'hair_baby')
HEADS = ['baby', 'toddler']
STYLES = ['fuzz', 'wisps', 'curl', 'curls', 'fringe']
NAMES = {'fuzz': 'Peach fuzz', 'wisps': 'Wisps', 'curl': 'Kewpie curl', 'curls': 'Curly cap', 'fringe': 'Little fringe'}
MAIN = '#8f4b29'
FILL = f'var(--hair-color,{MAIN})'
DARK = f'color-mix(in srgb,var(--hair-color,{MAIN}) 55%,#000)'
LIGHT = f'color-mix(in srgb,var(--hair-color,{MAIN}) 70%,#fff)'
INK = '#23140f'
f = lambda v: f'{v:.1f}'.rstrip('0').rstrip('.')


class Head:
    """One young head, measured: its outline row by row, and where the hair goes on it."""
    def __init__(self, name):
        self.rows = EL.scan(EL.head_polys(os.path.join(ROOT, 'assets', 'heads', f'{name}.svg')))
        marks, extra = EL.landmarks(self.rows)
        self.top = marks['crown_top']['y']
        self.cx = extra['cx']
        self.fore = marks['forehead_mid']['y']
        self.ear = marks['ear_left']['y']
        self.side = self.fore + 0.55 * (self.ear - self.fore)   # how far down the sides a cap comes
        self.centre = (self.cx, (self.top + self.ear) / 2)

    def edge(self, y, side):
        ys = sorted(self.rows)
        r = self.rows[min(ys, key=lambda v: abs(v - y))]
        return r[0] if side < 0 else r[1]

    def outline(self, y_to, off, step=6):
        """The skull's edge, `off` units outside it, from the left side at y_to over the crown to the right side."""
        left = [(self.edge(y, -1), y) for y in frange(y_to, self.top + 3, -step)]
        right = [(self.edge(y, 1), y) for y in frange(self.top + 3, y_to, step)]
        pts = left + [(self.cx, self.top)] + right
        return [self.push(p, off) for p in pts]

    def push(self, p, off):
        """A point moved `off` units away from the middle of the head (out from the skull)."""
        dx, dy = p[0] - self.centre[0], p[1] - self.centre[1]
        d = math.hypot(dx, dy) or 1
        return (p[0] + dx / d * off, p[1] + dy / d * off)


def frange(a, b, step):
    out, v = [], a
    while (step > 0 and v <= b) or (step < 0 and v >= b):
        out.append(v); v += step
    return out


def smooth(pts, move=True):
    """Catmull-Rom through points -> cubic path data (open)."""
    P = [pts[0]] + pts + [pts[-1]]
    d = [f'{"M" if move else "L"}{f(P[1][0])} {f(P[1][1])}']
    for i in range(1, len(pts)):
        p0, p1, p2, p3 = P[i - 1], P[i], P[i + 1], P[i + 2]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d.append(f'C{f(c1[0])} {f(c1[1])} {f(c2[0])} {f(c2[1])} {f(p2[0])} {f(p2[1])}')
    return ' '.join(d)


def scallops(pts, h, out=1):
    """A bumpy edge through points: a soft bump between each pair, `h` units out (or in, out=-1)."""
    d = []
    for a, b in zip(pts, pts[1:]):
        mx, my = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
        dx, dy = b[0] - a[0], b[1] - a[1]
        n = math.hypot(dx, dy) or 1
        nx, ny = dy / n * out, -dx / n * out   # perpendicular (left of travel = outward for an edge drawn left to right over the top)
        d.append(f'Q{f(mx + nx * h)} {f(my + ny * h)} {f(b[0])} {f(b[1])}')
    return ' '.join(d)


def hairline(H, y_side, inset, high, sag=0):
    """A baby's hairline: from the right side at y_side, curving up to `high` over the forehead, down to the left."""
    rx, lx = H.edge(y_side, 1) - inset, H.edge(y_side, -1) + inset
    return [(rx, y_side), (rx - (rx - H.cx) * 0.35, y_side - (y_side - high) * 0.7 + sag),
            (H.cx, high), (lx + (H.cx - lx) * 0.35, y_side - (y_side - high) * 0.7 + sag), (lx, y_side)]


def svg(name, head, base='', bangs='', lines=''):
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" data-baby-hair="{name}" data-head="{head}">
<!-- Generated by scripts/make_baby_hair.py from assets/heads/{head}.svg: do not edit by hand. -->
<g id="hair_back"/>
<g id="hair_base">{base}</g>
<g id="hair_bangs">{bangs}</g>
<g id="hair_lines" fill="none" stroke-linecap="round" stroke-linejoin="round">{lines}</g>
</svg>
'''


path = lambda d, fill=FILL, w=3: f'<path style="fill:{fill}" stroke="{INK}" stroke-width="{w}" stroke-linejoin="round" d="{d}"/>'
line = lambda d, color=DARK, w=2.2: f'<path style="stroke:{color}" stroke-width="{w}" d="{d}"/>'


def cap(H, y_side, off, high, inset):
    """A close cap: the skull's edge (off units out) over the top, back along a hairline. -> path data."""
    return smooth(H.outline(y_side, off)) + ' ' + smooth(hairline(H, y_side, inset, high)[::1], move=False) + ' Z'


def crescent(H, depth):
    """A thin band of fuzz over the crown, `depth` units deep at the top, thinning to nothing at the sides."""
    y_to = H.top + depth * 3.2
    outer = H.outline(y_to, 1.5, step=4)
    inner = [H.push(p, -depth * max(0.0, 1 - abs(p[0] - H.cx) / (abs(outer[0][0] - H.cx) or 1)) ** 0.8) for p in outer[::-1]]
    return smooth(outer) + ' ' + smooth(inner, move=False) + ' Z'


def style(name, H):
    span = H.ear - H.top
    if name == 'fuzz':
        y_side = H.side
        base = path(cap(H, y_side, 1.5, H.fore - 6, -1))
        strokes = []
        for i, t in enumerate([-0.55, -0.3, -0.08, 0.15, 0.38, 0.6]):
            x = H.cx + t * (H.edge(H.top + span * 0.25, 1) - H.cx)
            y = H.top + 10 + abs(t) * 22
            strokes.append(f'M{f(x)} {f(y)}q{f(4 + t * 6)} 6 {f(t * 10)} 14')
        return svg(name, H.name, base=base, lines=line(' '.join(strokes)))
    if name == 'wisps':
        base = path(crescent(H, 15))
        wisps = []
        for dx, h, lean in [(-18, 30, -13), (0, 42, 5), (17, 28, 14)]:
            x0, y0 = H.cx + dx, H.top + 8
            tip = (x0 + lean, y0 - h)
            wisps.append(f'M{f(x0 - 6)} {f(y0)}Q{f(x0 - 7 + lean * 0.3)} {f(y0 - h * 0.6)} {f(tip[0])} {f(tip[1])}Q{f(x0 + 3 + lean * 0.6)} {f(y0 - h * 0.45)} {f(x0 + 6)} {f(y0)}Z')
        return svg(name, H.name, base=base, bangs=path(' '.join(wisps), w=2.5), lines=line(f'M{f(H.cx - 20)} {f(H.top + 8)}q8 -3 16 0M{f(H.cx + 6)} {f(H.top + 7)}q8 -3 15 1', LIGHT, 2))
    if name == 'curl':
        base = path(crescent(H, 12))
        # One big curl on top, a spiral that springs from the crown and curls toward the forehead.
        cx, cy = H.cx + 6, H.top + 26
        pts = []
        for k in range(0, 46):
            a = math.pi * 1.1 + k * 0.17
            r = 3 + k * 0.62
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a) * 0.9))
        d = smooth(pts)
        curl = f'<path fill="none" stroke="{INK}" stroke-width="12" stroke-linecap="round" d="{d}"/><path fill="none" style="stroke:{FILL}" stroke-width="7" stroke-linecap="round" d="{d}"/>'
        return svg(name, H.name, base=base, bangs=curl)
    if name == 'curls':
        y_side = H.side + 6
        outer = H.outline(y_side, 3, step=12)
        inner = hairline(H, y_side, 12, H.fore - 2, sag=4)
        # Fill the bumpy edge out and the bumpy hairline in, then texture it with little curls.
        d = f'M{f(outer[0][0])} {f(outer[0][1])} ' + scallops(outer, 6, out=-1) + f' L{f(inner[0][0])} {f(inner[0][1])} ' + scallops(smooth_pts(inner, 3), 7, out=-1) + ' Z'
        base = path(d)
        curls = []
        for row in range(3):
            y = H.top + 16 + row * span * 0.16
            half = (H.edge(y, 1) - H.cx) * 0.8
            n = 4 + row
            for i in range(n):
                x = H.cx - half + (2 * half) * (i + 0.5) / n
                curls.append(f'M{f(x - 4)} {f(y + 2)}a4.5 4.5 0 1 1 6 3')
        return svg(name, H.name, base=base, lines=line(' '.join(curls), DARK, 2.2))
    if name == 'fringe':
        y_side = H.side - 6
        outer = H.outline(y_side, 2)
        # The fringe: straight-ish, short choppy points just above the brows.
        y_f = H.fore + (H.ear - H.fore) * 0.18
        rx, lx = H.edge(y_side, 1) + 1, H.edge(y_side, -1) - 1
        n = 7
        edge = [(rx, y_side), (rx - 18, y_f + 1)]
        for i in range(n + 1):
            x = (rx - 14) - (rx - lx - 28) * i / n
            edge.append((x, y_f + (5 if i % 2 else 0)))
        edge += [(lx + 18, y_f + 1), (lx, y_side)]
        d = smooth(outer) + ' ' + ' '.join(f'L{f(x)} {f(y)}' for x, y in edge) + ' Z'
        strands = ' '.join(f'M{f(H.cx + dx)} {f(H.top + 14)}Q{f(H.cx + dx * 1.15)} {f((H.top + y_f) / 2)} {f(H.cx + dx * 1.2)} {f(y_f - 4)}' for dx in (-48, -24, 0, 24, 48))
        return svg(name, H.name, base=path(d), lines=line(strands))
    raise ValueError(name)


def smooth_pts(pts, n):
    """More points along a gentle curve through pts (for an even row of bumps)."""
    out = []
    for a, b in zip(pts, pts[1:]):
        for k in range(n):
            t = k / n
            out.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
    return out + [pts[-1]]


def main():
    os.makedirs(OUT, exist_ok=True)
    for head in HEADS:
        H = Head(head)
        H.name = head
        for s in STYLES:
            with open(os.path.join(OUT, f'{s}_{head}.svg'), 'w', encoding='utf-8') as fh:
                fh.write(style(s, H))
    print(f'wrote {len(HEADS) * len(STYLES)} baby hairstyles to assets/hair_baby/')


if __name__ == '__main__':
    main()
