#!/usr/bin/env python3
"""Writes the outline of the world's land for the family map, from Natural Earth.

    npm pack world-atlas@2.0.2 && tar xzf world-atlas-2.0.2.tgz
    python3 scripts/build-land.py package/land-110m.json            # report only
    python3 scripts/build-land.py package/land-110m.json --write    # also write js/data/land.js

Source: Natural Earth 1:110m land (public domain), version 4.1.0, as TopoJSON
in the world-atlas package (ISC). Standard library only; the game loads the
result as a plain data file, never the package.

The outline is one SVG path in the map's equirectangular projection: a world
360 units wide and 180 high, x = longitude + 180, y = 90 - latitude. Points
closer together than TOLERANCE units are dropped, which at this scale removes
nothing visible. Rings that cross the antimeridian are broken there instead of
drawn across the map.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOLERANCE = 0.25


def decode(topo):
    """The arcs of a TopoJSON topology as lists of [longitude, latitude]."""
    t = topo.get('transform')
    arcs = []
    for arc in topo['arcs']:
        x = y = 0
        pts = []
        for p in arc:
            if t:
                x += p[0]
                y += p[1]
                pts.append([x * t['scale'][0] + t['translate'][0], y * t['scale'][1] + t['translate'][1]])
            else:
                pts.append([p[0], p[1]])
        arcs.append(pts)
    return arcs


def ring(indices, arcs):
    out = []
    for i in indices:
        pts = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
        out.extend(pts if not out else pts[1:])
    return out


def polygons(geom):
    if geom['type'] == 'GeometryCollection':
        for g in geom['geometries']:
            yield from polygons(g)
    elif geom['type'] == 'Polygon':
        yield geom['arcs']
    elif geom['type'] == 'MultiPolygon':
        yield from geom['arcs']


def main():
    if len(sys.argv) < 2:
        sys.exit('Give the path to land-110m.json (see the top of this file).')
    write = '--write' in sys.argv
    topo = json.load(open(sys.argv[1], encoding='utf-8'))
    arcs = decode(topo)
    obj = topo['objects']['land']
    parts = []
    points = 0
    for poly in polygons(obj):
        for r in poly:
            pts = ring(r, arcs)
            seg = []
            last = None
            for lon, lat in pts:
                x, y = lon + 180, 90 - lat
                if last and abs(x - last[0]) > 180:  # crossing the antimeridian: start a new piece
                    if len(seg) > 2:
                        parts.append(seg)
                    seg = []
                if not last or abs(x - last[0]) + abs(y - last[1]) >= TOLERANCE or (lon, lat) == tuple(pts[-1]):
                    seg.append((x, y))
                    last = (x, y)
            if len(seg) > 2:
                parts.append(seg)
    d = []
    for seg in parts:
        points += len(seg)
        d.append('M' + 'L'.join(f'{round(x, 1):g} {round(y, 1):g}' for x, y in seg) + 'Z')
    path = ''.join(d)
    print(f'{len(parts)} pieces of land, {points} points, {len(path) // 1024} KB of path data')
    if write:
        with open(os.path.join(ROOT, 'js/data/land.js'), 'w', encoding='utf-8') as f:
            f.write('// GENERATED by scripts/build-land.py from Natural Earth 1:110m land (public domain), version 4.1.0,\n'
                    '// via the world-atlas 2.0.2 TopoJSON. Do not edit by hand.\n'
                    '// One SVG path in a 360 x 180 equirectangular world: x = longitude + 180, y = 90 - latitude.\n'
                    f'export const LAND = {json.dumps(path)};\n')
        print('wrote js/data/land.js')


if __name__ == '__main__':
    main()
