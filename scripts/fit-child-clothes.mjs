// Fits children's clothes to the child's shoulders. Run after adding a baby or kid outfit: `npm run fit-child-clothes`.
//
// Children's outfits are drawn on a template of the child's own head (assets/clothes_templates/), so they are placed as
// drawn. But a drawing can come out a little narrower than the shoulders it was drawn on, and the body then shows at
// its edges. This measures, for each outfit, how much wider (and, a little, taller) it must be worn, about the middle of
// its neckline so the collar stays at the neck, for it to cover the shoulders; of the sizes that do, the smallest. Writes js/avatar/childClothesFit.js,
// which js/CharacterAvatar.js applies. Needs Playwright's Chromium.
import { createServer } from 'node:http';
import { readFile, writeFile } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
import { createRequire } from 'node:module';

/** Which head each kind of child's outfit is drawn on, and the middle of that head's neckline (512 frame). */
const HEADS = { baby: { file: 'heads/toddler.svg', x: 255.5, y: 459 }, kid: { file: 'heads/kid.svg', x: 256.1, y: 437 } };
const SY = [1, 1.04, 1.08, 1.12]; // a little taller is allowed; it is width that is missing (taller does not cover the sides)
const BARE = 0.5; // percent of the shoulders that may show (the edge of the outline, in practice)
const MAX = 1.6;

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const root = new URL('..', import.meta.url).pathname;
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml' };
const server = createServer(async (req, res) => {
  const path = normalize(join(root, decodeURIComponent(new URL(req.url, 'http://x').pathname)));
  if (!path.startsWith(root)) { res.writeHead(403); return res.end(); }
  try { const body = await readFile(path); res.writeHead(200, { 'content-type': TYPES[extname(path)] ?? 'application/octet-stream' }); res.end(body); }
  catch { res.writeHead(404); res.end(); }
}).listen(0);
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(`http://localhost:${server.address().port}/index.html`);
const result = await page.evaluate(async ({ HEADS, SY, BARE, MAX }) => {
  const { PART_BY_ID } = await import('/js/avatarManifest.js');
  const K = 2; const W = 512; const H = 512;
  const draw = async (text, tf = '') => {
    const svg = text.replace(/<svg\b[^>]*>/, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W * K}" height="${H * K}"><g${tf}>`).replace(/<\/svg>\s*$/, '</g></svg>');
    const img = new Image(); img.src = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml' })); await img.decode();
    const c = document.createElement('canvas'); c.width = W * K; c.height = H * K;
    const g = c.getContext('2d'); g.drawImage(img, 0, 0); return g.getImageData(0, 0, c.width, c.height).data;
  };
  const out = {};
  for (const [kind, h] of Object.entries(HEADS)) {
    const ids = Object.keys(PART_BY_ID).filter((id) => id.startsWith(`outfit_${kind}_`));
    if (!ids.length) continue;
    const head = await draw(await (await fetch('/assets/' + h.file)).text());
    // The shoulders: the body below the neckline, away from the neck itself (a neckline may show the chest by design).
    const shoulders = [];
    for (let y = Math.round((h.y + 14) * K); y < (H - 1) * K; y++) for (let x = 0; x < W * K; x++) {
      if (Math.abs(x / K - h.x) < 70) continue;
      if (head[(y * W * K + x) * 4 + 3] > 128) shoulders.push(y * W * K + x);
    }
    for (const id of ids) {
      const text = await (await fetch('/assets/' + PART_BY_ID[id].file)).text();
      const bare = async (sx, sy) => {
        const cl = await draw(text, ` transform="translate(${h.x} ${h.y}) scale(${sx} ${sy}) translate(${-h.x} ${-h.y})"`);
        return 100 * shoulders.filter((i) => cl[i * 4 + 3] < 128).length / shoulders.length;
      };
      let best = null;
      for (const sy of SY) {
        for (let sx = 1; sx <= MAX + 1e-9; sx = Math.round((sx + 0.02) * 100) / 100) {
          if ((await bare(sx, sy)) <= BARE) { if (!best || sx + sy < best.sx + best.sy) best = { sx, sy }; break; }
        }
      }
      out[id] = best ?? { sx: MAX, sy: SY[SY.length - 1], none: true };
    }
  }
  return out;
}, { HEADS, SY, BARE, MAX });
await browser.close();
server.close();

for (const [id, r] of Object.entries(result)) console.log(`${id.padEnd(32)} ${r.none ? `does not cover the shoulders even at ${MAX}x` : `${r.sx}x wide, ${r.sy}x tall`}`);
const fit = Object.fromEntries(Object.entries(result).filter(([, r]) => r.sx !== 1 || r.sy !== 1).map(([id, r]) => [id, { sx: r.sx, sy: r.sy }]));
const lines = ['// Generated by scripts/fit-child-clothes.mjs (`npm run fit-child-clothes`). Do not edit by hand.',
  '// Per children\'s outfit: how much wider (sx) and taller (sy) it is worn than drawn, about the middle of its neckline,',
  '// to cover the shoulders of the head it was drawn on. Applied by js/CharacterAvatar.js.',
  `export const CHILD_CLOTHES_FIT = ${JSON.stringify(fit)};`,
  `export const CHILD_NECKLINE = ${JSON.stringify(Object.fromEntries(Object.entries(HEADS).map(([k, h]) => [k, { x: h.x, y: h.y }])))};`, ''];
await writeFile(join(root, 'js/avatar/childClothesFit.js'), lines.join('\n'));
console.log('Wrote js/avatar/childClothesFit.js');
