#!/usr/bin/env python3
"""
Step 3 of the hair pipeline: picks the master base head and writes the ChatGPT prompt for new hairstyles.

    python3 scripts/select_base_head.py        (scripts/extract_landmarks.py also runs this when it finishes)

Reads assets/landmarks.json, averages each of the six landmarks over every head that has them, and picks the
head whose landmarks are closest to that average shape: the smallest sum of the six Euclidean distances. New
hair is drawn on that head, so the warp onto any other head is as small as it can be on average. Writes:

  assets/landmarks.json          "base_head": "<name>" (the head entries are kept as they are)
  assets/CHATGPT_HAIR_PROMPT.md  the prompt, with the base head's full SVG pasted in

Standard library only.
"""
import json, math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANDMARKS = os.path.join(ROOT, 'assets', 'landmarks.json')
HEADS = os.path.join(ROOT, 'assets', 'heads')
PROMPT = os.path.join(ROOT, 'assets', 'CHATGPT_HAIR_PROMPT.md')
POINTS = ['crown_top', 'forehead_mid', 'temple_left', 'temple_right', 'ear_left', 'ear_right']
OUTLINE = '#23140f'  # the heads' outline colour, so new hair matches the line work


def measured(data):
    """{head name: landmarks} for the heads that have numbers (a head with no SVG has nulls)."""
    return {n: v for n, v in data.items() if isinstance(v, dict) and all(v.get(p, {}).get('x') is not None for p in POINTS)}


def choose(heads):
    """-> (base head name, mean shape {point: (x, y)}, {head: total distance from the mean})."""
    mean = {p: (sum(h[p]['x'] for h in heads.values()) / len(heads), sum(h[p]['y'] for h in heads.values()) / len(heads)) for p in POINTS}
    dist = {n: sum(math.dist((h[p]['x'], h[p]['y']), mean[p]) for p in POINTS) for n, h in heads.items()}
    return min(dist, key=dist.get), mean, dist


def prompt(base, marks, svg):
    pts = '\n'.join(f'| `{p}` | {marks[p]["x"]} | {marks[p]["y"]} |' for p in POINTS)
    return f'''# ChatGPT hair prompt

Generated by `scripts/select_base_head.py`. Do not edit by hand: the head below is
`assets/heads/{base}.svg`, the master base head (the one closest to the average of all our heads).

**How to use:** copy everything inside the box below into ChatGPT, replace `[DESCRIBE THE HAIRSTYLE]`
with the style you want, and save the SVG it returns in `assets/hair_raw/` as `<short_name>.svg`
(lowercase, underscores: e.g. `wavy_bob.svg`). Then run `npm run fit-hair` to fit it to every head.
`assets/hair_raw/textured_crop.svg` is a finished example of the format.

**Several at once:** ask ChatGPT for several hairstyles in one reply, each under its file name (e.g. `### wavy_bob.svg`)
followed by its SVG. Paste the whole reply into `assets/raw_batch.txt` and run `npm run split-hair`: it saves each one to
`assets/hair_raw/` (skipping any cut off part-way, with a warning) and fits them all.

````text
You are drawing one hairstyle for a 2D game avatar. I am giving you the exact bald base head the hair must fit.
Draw ONLY the hair, as a single standalone SVG file, in the same coordinate system as the head.

HAIRSTYLE: [DESCRIBE THE HAIRSTYLE]

RULES (all required):
1. Output one complete SVG and nothing else: no explanation, no markdown fences.
2. Root element exactly: <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
   Use the head's coordinates directly. No transform attributes anywhere, no <image>, <use>, <text>, filters,
   gradients, masks, clipPaths or <style> blocks. Only <path> elements, inside these four groups, in this order:
     <g id="hair_back">   hair that is BEHIND the head: the back of the hair, and any lengths that fall behind the
                          neck and shoulders. Slightly darker shade. Drawn behind the head, so it only shows outside it.
     <g id="hair_base">   the main mass in FRONT of the head: the cap over the skull from the crown down to the
                          hairline, and the sideburns or side lengths.
     <g id="hair_bangs">  the fringe/bangs and any locks that fall over the forehead or face (may be empty).
                          Filled shapes with NO outline (stroke="none"), so they blend into hair_base.
     <g id="hair_lines">  drawn on top: thin lines for the part, strands and the bottom edge of the bangs
                          (fill="none"), and any highlights (filled shapes with stroke="none").
3. Do NOT include the head, face, ears, neck or any skin in your output. Hair only.
4. Fit the head exactly, using these landmarks of the base head (x, y in the 512 frame, y points down):
   - crown_top {marks["crown_top"]["x"]}, {marks["crown_top"]["y"]}: the hair must cover the top of the skull, sitting on or above this point.
   - forehead_mid {marks["forehead_mid"]["x"]}, {marks["forehead_mid"]["y"]}: the hairline. A fringe/bangs may come lower; otherwise keep the face below this clear.
   - temple_left {marks["temple_left"]["x"]}, {marks["temple_left"]["y"]} and temple_right {marks["temple_right"]["x"]}, {marks["temple_right"]["y"]}: the hair must wrap the skull outline at these points, about 5 units outside it (never leave a gap of bare scalp).
   - ear_left {marks["ear_left"]["x"]}, {marks["ear_left"]["y"]} and ear_right {marks["ear_right"]["x"]}, {marks["ear_right"]["y"]}: where the ears attach. Sideburns or the side hairline end here; longer hair may fall past it.
   - Keep the face itself (eyes, nose and mouth area, roughly x 175-335, y 250-415) clear, except for a fringe or strands that deliberately fall over it.
5. Long hair may fall behind the shoulders down to the bottom of the frame (y 512); keep everything within x 0-512.
6. Colours: use exactly these four and no others, so the game can dye the hair any colour:
     #8f4b29  the main fill: every shape in hair_base and hair_bangs
     #6b3520  the fill of hair_back
     #4a2414  the internal lines in hair_lines
     #b8693d  highlights in hair_lines (filled shapes, no line around them)
   (The outline colour {OUTLINE} in rule 7 is the only other colour, and only on the outer silhouette.)
7. Lines: the hair has ONE bold outer silhouette and soft, subtle detail inside it.
   - Outline ONLY the outer silhouette: put stroke="{OUTLINE}" stroke-width="6" stroke-linejoin="round" on the shapes
     in hair_base and hair_back, and nowhere else (the same dark brown and weight as the head's outline).
   - Do NOT put the {OUTLINE} 6-unit outline on internal pieces or bangs, or anywhere hair overlaps hair: every shape
     in hair_bangs has stroke="none", so it blends smoothly into hair_base.
   - Draw the part, strand lines and the bottom edge of the bangs as thin lines in hair_lines:
     stroke="#4a2414" stroke-width="2.5" stroke-linecap="round" fill="none".
   - No harsh internal cut-outs: separate locks by overlapping borderless shapes or by these thin lines, not by
     gaps or holes cut through the hair.
8. Style: match the head's flat, clean cartoon look: smooth curves, one bold silhouette, no texture noise, no tiny
   specks.
9. For a buzz cut or skin fade (hair that hugs the skull), add data-clip-to-head="true" to the root <svg>: the game
   then clips the hair to the head's exact outline, so it can be drawn slightly oversized with no overhang.

Here is the base head (`{base}`). Use it only as the reference shape; do not return it:

{svg}
````

## Base head landmarks (`{base}`)

| Landmark | x | y |
|---|---|---|
{pts}
'''


def main():
    with open(LANDMARKS, encoding='utf-8') as f:
        data = json.load(f)
    heads = measured(data)
    if not heads:
        raise SystemExit('no measured heads in assets/landmarks.json: run scripts/extract_landmarks.py first')
    base, mean, dist = choose(heads)
    out = {'base_head': base, **{k: v for k, v in data.items() if k != 'base_head'}}
    with open(LANDMARKS, 'w', encoding='utf-8') as f:
        json.dump(out, f, indent=2)
        f.write('\n')
    svg = open(os.path.join(HEADS, f'{base}.svg'), encoding='utf-8').read().strip()
    with open(PROMPT, 'w', encoding='utf-8') as f:
        f.write(prompt(base, heads[base], svg))
    print(f'mean shape over {len(heads)} heads: ' + '  '.join(f'{p}=({x:.1f},{y:.1f})' for p, (x, y) in mean.items()))
    for n in sorted(dist, key=dist.get):
        print(f'  {n:<12} {dist[n]:6.2f}' + ('   <- base head' if n == base else ''))
    print(f'wrote base_head "{base}" to {os.path.relpath(LANDMARKS, ROOT)} and {os.path.relpath(PROMPT, ROOT)}')


if __name__ == '__main__':
    main()
